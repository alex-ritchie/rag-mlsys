"""Render docs/benchmarks/cell-*.json (from scripts/ablation_cell.sh) into docs/benchmarks/ablation-serving.md."""

from __future__ import annotations

import json

from mlsys_common.settings import REPO_ROOT

DOCS = REPO_ROOT / "docs" / "benchmarks"
OUT = DOCS / "ablation-serving.md"


def _row(r: dict) -> str:
    fb = r.get("rerank_fallbacks")
    note = f" ({fb} rerank fallbacks)" if fb else ""
    return f"| {r['concurrency']} | {r['requests_per_s']} | {r['output_tokens_per_s']} | {r['ttft_ms']['p50']} | {r['ttft_ms']['p99']} | {r['total_ms']['p50']} | {r['total_ms']['p99']} | {r['errors']}{note} |"


def render(cells: list[dict]) -> str:
    out = [
        "# Serving ablation — per-cell results",
        "",
        "Generated by `python -m mlsys_bench.cells` from `docs/benchmarks/cell-*.json` (each produced by",
        "`scripts/ablation_cell.sh`, which embeds the serving config, placement, VRAM and the bench result files).",
        "Latencies in ms. `llm-only` = vLLM's OpenAI endpoint with plain prompts, no retrieval (512-token answers,",
        "thinking off). `rag-e2e` = the full RAG pipeline through the gateway: embed → hybrid retrieval → rerank →",
        "generation, with the cell's embedder/reranker placement.",
        "",
        "## Summary",
        "",
        "| cell | weights | KV cache | max conc. @ full ctx | placement (emb / rerank) | VRAM vLLM / +services / peak | llm-only tok/s @c8 | llm-only TTFT p50 @c1 | rag-e2e TTFT p50 @c1 | rag-e2e total p50 @c8 | errors |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for c in cells:
        d = {r["concurrency"]: r for r in c.get("llm_only", c.get("engine_direct", []))}
        g = {r["concurrency"]: r for r in c.get("rag_e2e", c.get("gateway_e2e", []))}
        v = c["vram_mib"]
        pl = c["placement"]
        out.append(
            f"| `{c['tag']}` | {c['weights'].replace('Model loading took ', '')} | {c['kv'].replace('Available KV cache memory: ', '')} ({c['kv_tokens'].replace('GPU KV cache size: ', '')}) | {c['max_concurrency_at_full_context'].split(': ')[-1]} | {pl['embedder']} / {pl['reranker']}@{pl['reranker_max_length']} | {v.get('vllm_only') or '?'} / {v['with_embedder_reranker']} / {v['peak_gateway_load']} MiB | {d.get(8, {}).get('output_tokens_per_s', '-')} | {d.get(1, {}).get('ttft_ms', {}).get('p50', '-')} | {g.get(1, {}).get('ttft_ms', {}).get('p50', '-')} | {g.get(8, {}).get('total_ms', {}).get('p50', '-')} | {c['oom_or_cuda_errors']} oom, {c['gateway_500s']} 5xx |"
        )
    for c in cells:
        out += [
            "",
            f"## `{c['tag']}` — `{c['serving_config']}`",
            "",
            f"- model `{c['model']}` · vLLM {c.get('vllm_version') or '?'} · load {c['load_seconds']} s · vLLM alive after run: {c['vllm_alive_after']}",
            "",
            "### LLM-only (vLLM endpoint, no retrieval)",
            "",
            "| conc | req/s | out tok/s | TTFT p50 | TTFT p99 | total p50 | total p99 | errors |",
            "|---|---|---|---|---|---|---|---|",
        ]
        out += [_row(r) for r in c.get("llm_only", c.get("engine_direct", []))]
        out += [
            "",
            "### RAG end-to-end (through the gateway)",
            "",
            "| conc | req/s | out tok/s | TTFT p50 | TTFT p99 | total p50 | total p99 | errors |",
            "|---|---|---|---|---|---|---|---|",
        ]
        rag = c.get("rag_e2e", c.get("gateway_e2e", []))
        out += [_row(r) for r in rag]
        stages = rag[0].get("stage_ms_p50", {}) if rag else {}
        if stages:
            out += [
                "",
                "Per-stage p50 at c1: "
                + ", ".join(f"{k.replace('_ms', '')} {v:.0f}" for k, v in stages.items()),
            ]
    return "\n".join(out) + "\n"


def main() -> None:
    cells = [json.loads(p.read_text()) for p in sorted(DOCS.glob("cell-*.json"))]
    OUT.write_text(render(cells))
    print(f"wrote {OUT} ({len(cells)} cells)")


if __name__ == "__main__":
    main()
