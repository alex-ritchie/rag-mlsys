"""`make bench-report`: render bench/results/*.json into docs/benchmarks/results.md (markdown tables)."""

from __future__ import annotations

import json

from mlsys_common.settings import REPO_ROOT

RESULTS = REPO_ROOT / "bench" / "results"
OUT = REPO_ROOT / "docs" / "benchmarks" / "results.md"


def table(result: dict) -> str:
    rows = [
        "| conc | req/s | out tok/s | TTFT p50 | TTFT p99 | total p50 | total p99 | errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in result["runs"]:
        rows.append(
            f"| {r['concurrency']} | {r['requests_per_s']} | {r['output_tokens_per_s']} | {r['ttft_ms']['p50']} | {r['ttft_ms']['p99']} | {r['total_ms']['p50']} | {r['total_ms']['p99']} | {r['errors']} |"
        )
    return "\n".join(rows)


def render(results: list[dict]) -> str:
    out = [
        "# Benchmark results",
        "",
        "Generated by `make bench-report` from `bench/results/*.json`. Latencies in ms.",
        "",
    ]
    for r in sorted(results, key=lambda x: x["name"]):
        cfg = r["config"]
        out += [
            f"## {r['name']}",
            "",
            f"- target: `{cfg.get('target', 'gateway')}` @ `{cfg['base_url']}` · model `{cfg.get('model') or r.get('server', {}).get('health', {}).get('model', '?')}`",
            f"- code `{r['git_sha'][:10]}` · {r['created_at']} · GPU {r.get('gpu', {}).get('name', '?')}",
        ]
        if r.get("serving_config"):
            sc = r["serving_config"]
            out.append(
                f"- serving config: `{sc.get('engine')}` args `{json.dumps(sc.get('args', {}))}`"
            )
        out += [f"- reproduce: `{r['reproduce']}`", "", table(r), ""]
    return "\n".join(out)


def main() -> None:
    results = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*.json"))]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(results))
    print(f"wrote {OUT} ({len(results)} runs)")


if __name__ == "__main__":
    main()
